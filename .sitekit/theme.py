"""The base theme's named spots and the plugins/ folder loader (site-kit#2, the proof on S'mores).

A site is a base theme with named spots in its pages. A feature is a folder, plugins/<name>/, that fills some of those spots:

    plugins/location-picker/
        plugin.json    the manifest: name, version, the spots it fills (and their priority), its assets, its edge code, its settings
        plugin.py      the code: `hooks = {spot: fn(ctx) -> html}` and, if it generates files, `files(ctx) -> {name: text}` (JSON for
                       its edge code), `public(ctx) -> {name: text}` (JSON served with its assets) and `edge_on(ctx) -> bool`
                       (False: this site runs none of its edge code)
        picker.css     an asset, copied to site/assets/plugins/location-picker/
        nearest.js     edge code (a Cloudflare Pages Function module), copied to functions/plugins/location-picker/; `edge.also` names
                       more modules it imports, copied beside it
        tests/         its own tests

Folder there, the feature is on. Folder gone, every spot gives its default and nothing breaks. Two plugins that fill the same
spot at the same priority stop the build and name both. A plugin's settings come from the site, by name, and are checked
against the plugin's own schema: anything missing, unknown or of the wrong type stops the build, so a half-configured plugin
never ships. Nothing here reads a key; a plugin names the setting and the site (or the host) fills it in.

This file has no dependencies and no knowledge of any one site. It lives in site-kit's theme/ and a site keeps a copy; the paths above (functions/, site/) are the consuming site's."""
import importlib.util
import json
import pathlib
import re

# The spots the base theme renders in its pages. A plugin may fill only these; a name that is not here stops the build.
# A site's build puts each spot's render() into its page template (S'mores: head.styles is ${head_styles}, body.end is ${body_end}).
SPOTS = ("head.styles", "header.topbar", "body.end")
SPOT_ABOUT = {"head.styles": "the page head, after the core stylesheet: link tags for a plugin's own stylesheet, a <style> of its settings, and a small same-origin script that must run before the first paint (time-of-day sets html[data-daypart]); never an inline script",
              "header.topbar": "the top bar of the header (the nearest-campfire slot on S'mores); the core's default is used when no plugin fills it",
              "body.end": "markup and script tags at the end of every page, just before </body> (the Talk bubble); empty when no plugin fills it"}
# What a plugin may filter: a finished page's HTML, `fn(html, ctx) -> html`, each plugin's output the next one's input.
FILTERS = ("page.html",)
FILTER_ABOUT = {"page.html": "a finished page's HTML, each plugin's output the next one's input (content-blocks marks {{namespace:name}} here)"}

# What functions/_plugins.js starts with: the generated list of the plugins' edge code that functions/_middleware.js runs.
PLUGINS_JS_HEADER = ("// Generated by scripts/build.py from plugins/*/plugin.json. Do not edit: the build rewrites it, and `build.py --check`\n"
                     "// fails if it differs. The edge code of each plugin folder, in name order, for functions/_middleware.js to run.\n")

NAME = re.compile(r"^[a-z0-9][a-z0-9-]*$")
VERSION = re.compile(r"^\d+\.\d+\.\d+$")
TYPES = {"string": str, "integer": int, "number": (int, float), "boolean": bool}


def _is(value, kind):
    """value is of the schema type kind; a boolean is not a number."""
    return isinstance(value, TYPES[kind]) and not (kind in ("integer", "number") and isinstance(value, bool))


class ThemeError(Exception):
    """A plugin or its settings are wrong. The build stops and prints this; nothing is half-built."""


# A name a plugin gives for a file: plain relative segments of letters, digits, - _ and . (never starting with a dot), so it
# cannot climb out of a folder, hide, or break the quotes of the JavaScript the build writes around it.
PLAIN = re.compile(r"^[A-Za-z0-9_-][A-Za-z0-9_.-]*(/[A-Za-z0-9_-][A-Za-z0-9_.-]*)*$")
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def _inside(rel, plugin, what):
    """rel, if it is a plain relative path that stays inside the plugin's folder (or its output folder); else ThemeError."""
    if not isinstance(rel, str) or not PLAIN.fullmatch(rel) or ".." in rel.split("/"):
        raise ThemeError(f'plugin "{plugin}": {what} "{rel}" must be a plain relative path inside the plugin folder '
                         f'(letters, digits, - _ . and /)')
    return rel


def _shape(value, kind, plugin, what):
    """value as the given kind (dict or list); an absent value (None) is an empty one, anything else of the wrong kind is an error."""
    if value is None:
        return kind()
    if not isinstance(value, kind):
        raise ThemeError(f'plugin "{plugin}": {what} must be {"an object" if kind is dict else "a list"}, not {type(value).__name__}')
    return value


class Scoped:
    """What a hook is handed: the site's own context, plus `config`, this plugin's settings. Nothing else is shared."""

    def __init__(self, ctx, config):
        object.__setattr__(self, "_ctx", ctx)
        object.__setattr__(self, "config", config)

    def __getattr__(self, name):
        return getattr(self._ctx, name)


class Plugin:
    def __init__(self, folder, given):
        self.folder = folder
        manifest_path = folder / "plugin.json"
        if not manifest_path.is_file():
            raise ThemeError(f'plugins/{folder.name}: a folder in plugins/ with no plugin.json is not a plugin (remove it or add the manifest)')
        try:
            self.manifest = json.loads(manifest_path.read_text())
        except json.JSONDecodeError as err:
            raise ThemeError(f"plugins/{folder.name}/plugin.json is not valid JSON: {err}") from err
        m = _shape(self.manifest, dict, folder.name, "plugin.json")
        self.name = m.get("name")
        if not isinstance(self.name, str) or not NAME.fullmatch(self.name):
            raise ThemeError(f'plugins/{folder.name}/plugin.json: name "{self.name}" must be a lowercase slug (a-z, 0-9, hyphens)')
        if self.name != folder.name:
            raise ThemeError(f'plugins/{folder.name}/plugin.json: name "{self.name}" must be the folder name "{folder.name}"')
        if not isinstance(m.get("version"), str) or not VERSION.fullmatch(m["version"]):
            raise ThemeError(f'plugin "{self.name}": version "{m.get("version")}" must be three numbers like 1.0.0')
        self.version = m["version"]
        self.hooks = {}
        for spot, options in _shape(m.get("hooks"), dict, self.name, "hooks").items():
            if spot not in SPOTS:
                raise ThemeError(f'plugin "{self.name}" fills "{spot}", which the base theme does not have. Spots: {", ".join(SPOTS)}')
            priority = _shape(options, dict, self.name, f'hooks "{spot}"').get("priority", 10)
            if not isinstance(priority, int) or isinstance(priority, bool):
                raise ThemeError(f'plugin "{self.name}": the priority of "{spot}" must be a whole number')
            self.hooks[spot] = priority
        self.filters = {}
        for name, options in _shape(m.get("filters"), dict, self.name, "filters").items():
            if name not in FILTERS:
                raise ThemeError(f'plugin "{self.name}" filters "{name}", which the base theme does not have. Filters: {", ".join(FILTERS)}')
            priority = _shape(options, dict, self.name, f'filters "{name}"').get("priority", 10)
            if not isinstance(priority, int) or isinstance(priority, bool):
                raise ThemeError(f'plugin "{self.name}": the priority of filter "{name}" must be a whole number')
            self.filters[name] = priority
        self.assets = [_inside(a, self.name, "asset") for a in _shape(m.get("assets"), list, self.name, "assets")]
        for a in self.assets:
            self.assets_text(a)
        self.edge = m.get("edge")
        if self.edge is not None:
            edge = _shape(self.edge, dict, self.name, "edge")
            module = _inside(edge.get("module"), self.name, "edge module")
            data, key = edge.get("data"), edge.get("key")
            if data is not None and not _inside(data, self.name, "edge data file").endswith(".json"):
                raise ThemeError(f'plugin "{self.name}": edge data file "{data}" must be a .json file')
            if key is not None and not (isinstance(key, str) and IDENT.fullmatch(key)):
                raise ThemeError(f'plugin "{self.name}": edge key "{key}" must be a plain name (letters, digits, underscore)')
            if not (folder / module).is_file():
                raise ThemeError(f'plugin "{self.name}": edge module "{module}" is not in the plugin folder')
            also = _shape(edge.get("also"), list, self.name, "edge also")
            seen = {module}
            for x in also:
                x = _inside(x, self.name, "edge extra file")
                if not x.endswith((".js", ".mjs")):
                    raise ThemeError(f'plugin "{self.name}": edge extra file "{x}" must be code (.js or .mjs)')
                if x == module:
                    raise ThemeError(f'plugin "{self.name}": edge extra file "{x}" is the edge module itself')
                if x in seen:
                    raise ThemeError(f'plugin "{self.name}": edge extra file "{x}" is listed twice')
                if not (folder / x).is_file():
                    raise ThemeError(f'plugin "{self.name}": edge extra file "{x}" is not in the plugin folder')
                seen.add(x)
            required = edge.get("required", False)
            if not isinstance(required, bool):
                raise ThemeError(f'plugin "{self.name}": edge required must be true or false')
            # "behind": the name of the required gate this plugin runs behind (site-kit#432). It runs only inside that gate's
            # pass, never in runEdge, so it never answers a request the gate refused.
            behind = edge.get("behind")
            if behind is not None and (not isinstance(behind, str) or not NAME.fullmatch(behind) or behind == self.name or required):
                raise ThemeError(f'plugin "{self.name}": edge behind must name another plugin, a required gate (e.g. "members"), '
                                 'and a required plugin runs behind nothing')
            self.edge = {"module": module, "data": data, "key": key, "also": also, "required": required, "behind": behind}
        config = _shape(m.get("config"), dict, self.name, "config")
        self.fields = _shape(config.get("fields"), dict, self.name, "config fields")
        for key, field in self.fields.items():
            _shape(field, dict, self.name, f'setting "{key}"')
            if field.get("type") not in TYPES:
                raise ThemeError(f'plugin "{self.name}": setting "{key}" has an unknown type "{field.get("type")}" (string, integer, number or boolean)')
            if "default" in field and not _is(field["default"], field["type"]):
                raise ThemeError(f'plugin "{self.name}": the default of setting "{key}" must be a {field["type"]}, got {field["default"]!r}')
        self.settings = self._settings(given)
        self.code = self._import()
        declared = set(self.hooks)
        given_hooks = set(getattr(self.code, "hooks", {}) or {})
        for spot in sorted(declared - given_hooks):
            raise ThemeError(f'plugin "{self.name}": plugin.json fills "{spot}" but plugin.py has no hook for it')
        for spot in sorted(given_hooks - declared):
            raise ThemeError(f'plugin "{self.name}": plugin.py has a hook for "{spot}" that is not declared in plugin.json (declare it there, or drop the hook)')
        given_filters = set(getattr(self.code, "filters", {}) or {})
        for name in sorted(set(self.filters) - given_filters):
            raise ThemeError(f'plugin "{self.name}": plugin.json filters "{name}" but plugin.py has no filter for it')
        for name in sorted(given_filters - set(self.filters)):
            raise ThemeError(f'plugin "{self.name}": plugin.py has a filter for "{name}" that is not declared in plugin.json (declare it there, or drop the filter)')

    def assets_text(self, rel):
        """An asset's text. It must be a file inside the plugin's real folder (a symlink out is refused) and must be text."""
        path = self.folder / rel
        if not path.is_file() or not path.resolve().is_relative_to(self.folder.resolve()):
            raise ThemeError(f'plugin "{self.name}": asset "{rel}" is not a file inside the plugin folder')
        try:
            return path.read_text()
        except UnicodeDecodeError as err:
            raise ThemeError(f'plugin "{self.name}": asset "{rel}" must be text (css, js, svg); binary files are not supported') from err

    def _import(self):
        path = self.folder / "plugin.py"
        if not path.is_file():
            raise ThemeError(f'plugin "{self.name}": plugins/{self.name}/plugin.py is missing')
        spec = importlib.util.spec_from_file_location(f"plugin_{self.name.replace('-', '_')}", path)
        module = importlib.util.module_from_spec(spec)
        try:
            spec.loader.exec_module(module)
        except (Exception, SystemExit) as err:   # the plugin's own code failed: stop, name it, never skip it
            raise ThemeError(f'plugin "{self.name}": plugin.py could not be loaded: {type(err).__name__}: {err}') from err
        return module

    def _settings(self, given):
        """The site's values for this plugin, checked against its schema, with the defaults filled in."""
        given = dict(given or {})
        for key in sorted(set(given) - set(self.fields)):
            raise ThemeError(f'plugin "{self.name}": the site sets "{key}", which the plugin does not have. Settings: '
                             f'{", ".join(sorted(self.fields)) or "none"}')
        out = {}
        for key, field in sorted(self.fields.items()):
            kind = field.get("type")
            if key in given:
                value = given[key]
                if not _is(value, kind):
                    raise ThemeError(f'plugin "{self.name}": setting "{key}" must be a {kind}, got {value!r}')
                out[key] = value
            elif "default" in field:
                out[key] = field["default"]
            elif field.get("required"):
                raise ThemeError(f'plugin "{self.name}": the site must set "{key}" (a required setting with no default)')
        return out

    def _made(self, fn, ctx, what):
        """The JSON files plugin.py's fn(ctx) makes: {name: text}, each a plain path inside the plugin's folder."""
        make = getattr(self.code, fn, None)
        if not make:
            return {}
        try:
            made = make(Scoped(ctx, self.settings))
        except Exception as err:
            raise ThemeError(f'plugin "{self.name}": {fn}() failed: {type(err).__name__}: {err}') from err
        out = {}
        for rel, text in _shape(made, dict, self.name, f"what {fn}() returns").items():
            _inside(rel, self.name, what)
            if not rel.endswith(".json"):
                raise ThemeError(f'plugin "{self.name}": {what} "{rel}" must be a .json file (data, not code)')
            if not isinstance(text, str):
                raise ThemeError(f'plugin "{self.name}": the text of {what} "{rel}" must be a string, not {type(text).__name__}')
            out[rel] = text
        return out

    def generated(self, ctx):
        """The files plugin.py generates for its edge code (`files(ctx)`): {name: text}, JSON only, never the edge module itself."""
        return self._made("files", ctx, "generated file")

    def published(self, ctx):
        """The data files plugin.py publishes with the site's assets (`public(ctx)`), served under /assets/plugins/<name>/: JSON
        only. For data another service reads from the site, such as Talk's talk-data.json for the shared Talk service."""
        return self._made("public", ctx, "public file")

    def edge_on(self, ctx):
        """Whether this site runs the plugin's edge code: it has some, and plugin.py's `edge_on(ctx)`, if any, does not say False
        (a Talk site on the shared service answers no endpoint itself)."""
        check = getattr(self.code, "edge_on", None)
        if not self.edge:
            return False
        if check is None:
            return True
        try:
            on = check(Scoped(ctx, self.settings))
        except Exception as err:
            raise ThemeError(f'plugin "{self.name}": edge_on() failed: {type(err).__name__}: {err}') from err
        if not isinstance(on, bool):
            raise ThemeError(f'plugin "{self.name}": edge_on() must return True or False, not {type(on).__name__}')
        return on


class Theme:
    def __init__(self, plugins):
        self.plugins = sorted(plugins, key=lambda p: p.name)
        by_spot = {}
        for p in self.plugins:
            for spot, priority in {**p.hooks, **p.filters}.items():
                by_spot.setdefault(spot, {}).setdefault(priority, []).append(p.name)
        for spot, by_priority in by_spot.items():
            for priority, names in by_priority.items():
                if len(names) > 1:
                    raise ThemeError(f'plugins {" and ".join(names)} both fill "{spot}" at priority {priority}: give one a different priority in its plugin.json')

    def names(self):
        return [p.name for p in self.plugins]

    def versions(self):
        return {p.name: p.version for p in self.plugins}

    def render(self, spot, ctx, default=""):
        """What goes in a spot: each plugin's output, lowest priority first, joined by newlines; the default if nobody fills it."""
        if spot not in SPOTS:
            raise ThemeError(f'"{spot}" is not a spot of the base theme. Spots: {", ".join(SPOTS)}')
        filling = sorted((p.hooks[spot], p.name, p) for p in self.plugins if spot in p.hooks)
        if not filling:
            return default
        parts = []
        for _, _, p in filling:
            try:
                html = p.code.hooks[spot](Scoped(ctx, p.settings))
            except ThemeError:
                raise
            except Exception as err:
                raise ThemeError(f'plugin "{p.name}" failed filling "{spot}": {type(err).__name__}: {err}') from err
            if not isinstance(html, str):
                raise ThemeError(f'plugin "{p.name}" must return a string for "{spot}", not {type(html).__name__}')
            if html:
                parts.append(html)
        return "\n".join(parts) if parts else default

    def filter(self, name, html, ctx):
        """A finished page through every plugin's filter of that name, lowest priority first, each on the last one's output."""
        if name not in FILTERS:
            raise ThemeError(f'"{name}" is not a filter of the base theme. Filters: {", ".join(FILTERS)}')
        for _, _, p in sorted((p.filters[name], p.name, p) for p in self.plugins if name in p.filters):
            try:
                out = p.code.filters[name](html, Scoped(ctx, p.settings))
            except ThemeError:
                raise
            except Exception as err:
                raise ThemeError(f'plugin "{p.name}" failed filtering "{name}": {type(err).__name__}: {err}') from err
            if not isinstance(out, str):
                raise ThemeError(f'plugin "{p.name}" must return a string for filter "{name}", not {type(out).__name__}')
            html = out
        return html

    def site_files(self, ctx):
        """Files for site/: each plugin's assets and the data it publishes, under assets/plugins/<name>/. {path under site/: text}."""
        out = {}
        for p in self.plugins:
            for rel in p.assets:
                out[f"assets/plugins/{p.name}/{rel}"] = p.assets_text(rel)
            for rel, text in p.published(ctx).items():
                if f"assets/plugins/{p.name}/{rel}" in out:
                    raise ThemeError(f'plugin "{p.name}": public file "{rel}" has the name of one of its assets')
                out[f"assets/plugins/{p.name}/{rel}"] = text
        return out

    def function_files(self, ctx):
        """Files for functions/: each plugin's edge module and the data it generates, under plugins/<name>/, and the generated
        _plugins.js that lists them. {path under functions/: text}. Nothing outside a plugin's own folder is ever written."""
        out = {}
        imports, items = [], []
        gates = {p.name for p in self.plugins if p.edge_on(ctx) and p.edge["required"]}
        for p in self.plugins:
            if p.edge_on(ctx) and p.edge["behind"] and p.edge["behind"] not in gates:
                raise ThemeError(f'plugin "{p.name}" runs behind "{p.edge["behind"]}", which this site doesn\'t run as a required '
                                 'gate: add and configure it, or remove this plugin (it is never served ungated)')
        for i, p in enumerate(p for p in self.plugins if p.edge_on(ctx)):
            module, data, key = p.edge["module"], p.edge["data"], p.edge["key"]
            out[f"plugins/{p.name}/{module}"] = (p.folder / module).read_text()
            for extra in p.edge["also"]:
                out[f"plugins/{p.name}/{extra}"] = (p.folder / extra).read_text()
            imports.append(f'import {{ handle as h{i} }} from "./plugins/{p.name}/{module}";')
            entry = f'name: "{p.name}", handle: h{i}'
            if data:
                for rel, text in p.generated(ctx).items():
                    out[f"plugins/{p.name}/{rel}"] = text
                if f"plugins/{p.name}/{data}" not in out:
                    raise ThemeError(f'plugin "{p.name}": its edge data file "{data}" is not among the files plugin.py generates')
                imports.append(f"const d{i} = {inline_json(p.name, out[f'plugins/{p.name}/{data}'])};")
                entry += f", data: d{i}" + (f".{key}" if key else "")
            if p.edge["required"]:
                entry += ", required: true"
            if p.edge["behind"]:
                entry += f', behind: "{p.edge["behind"]}"'
            items.append("{ " + entry + " }")
        body = ("export const edge = [\n  " + ",\n  ".join(items) + ",\n];\n") if items else "export const edge = [];\n"
        out["_plugins.js"] = PLUGINS_JS_HEADER + "".join(i + "\n" for i in imports) + body
        return out


def inline_json(name, text):
    """A plugin's edge data as JS for _plugins.js: JSON.parse of the data as one string literal. Never an import with `with
    { type: "json" }`: Cloudflare Pages' own build bundles with an esbuild that can't parse import attributes, so a site it
    builds fails (key-site#17). Never an object literal either: there a "__proto__" key sets the prototype and the key is lost
    (maint-review-2 on site-kit#450); JSON.parse keeps it as a key. ASCII-only, and a backtick or "*" is a \\u escape, so the
    list never holds what site_check reads as a template literal or a block comment."""
    try:
        value = json.loads(text)
    except ValueError as e:
        raise ThemeError(f'plugin "{name}": its edge data file is not JSON: {e}') from None
    literal = json.dumps(json.dumps(value, separators=(",", ":"), ensure_ascii=True), ensure_ascii=True)
    return "JSON.parse(" + literal.replace("`", "\\u0060").replace("*", "\\u002a") + ")"


def load(plugins_dir, config=None, only=None):
    """Find, validate and import every plugin folder in plugins_dir. A missing folder is a site with no features. `config` is
    {plugin name: {setting: value}}; settings for a plugin that is not installed stop the build. `only`, a set of folder
    names, loads just those: site-templates' edge build loads the plugins with edge code, not a slot plugin whose settings
    live in its slot's own config file (site-kit#298)."""
    plugins_dir = pathlib.Path(plugins_dir)
    config = dict(config or {})
    folders = sorted(p for p in plugins_dir.iterdir() if p.is_dir() and not p.name.startswith(("_", "."))) if plugins_dir.is_dir() else []
    folders = [p for p in folders if only is None or p.name in only]
    plugins = [Plugin(f, config.get(f.name)) for f in folders]
    for name in sorted(set(config) - {p.name for p in plugins}):
        raise ThemeError(f'settings for plugin "{name}", which is not in plugins/ (remove them, or restore the folder)')
    return Theme(plugins)
