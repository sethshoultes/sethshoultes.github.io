"""The site's edge code (site-kit#298 PR 2): what a site-templates site serves through Pages Functions, made by the same
theme loader a theme site's build uses, so a members gate or a waitlist works here exactly as it does there.

    python3 build.py ... --functions functions            write functions/ with the site
    python3 build.py ... --functions functions --check    fail if the committed functions/ differs from what it would write

The site's settings for its plugins are .sitekit/plugins.json, {plugin: {setting: value}}, checked against each plugin's own
schema (a setting a plugin doesn't have stops the build). The theme loader and the chain are the kit's, vendored by site_sync
as .sitekit/theme.py and .sitekit/chain.js, never a copy the site edits. The build owns, and rewrites:
- functions/_plugins.js and functions/plugins/<name>/ (each edge plugin's module, its extra files and its data);
- functions/_chain.js (the kit's chain);
- functions/_middleware.js, the kit's recipe: the required plugins first (runRequired), then agent-files when the site has
  it, then the other plugins (runEdge), then the page.
It writes only those files. A file under functions/plugins/ the build doesn't make (the site's own, or one a removed plugin
left) is never deleted: the build refuses and names it, and so does a symlink anywhere on a path it would write (the lead on
site-kit#399). Standard library only."""
import importlib.util
import inspect
import json
import os
import pathlib
import types

OWNED = ("_plugins.js", "_chain.js", "_middleware.js")
HEAD = ("// Generated by site-templates' build.py --functions (site-kit#298). Do not edit: the build rewrites it, and\n"
        "// --check fails if it differs. The required plugins (a members gate) run first, then agent-files, then the rest.\n")
IMPORTS = 'import { runEdge, runRequired } from "./_chain.js";\nimport { edge } from "./_plugins.js";\n'
AGENT_FILES = 'import { agentFiles, discoveryHeaders, vary } from "../plugins/agent-files/functions/agent-files.js";\n'
WITH_AGENT_FILES = ("export async function onRequest(context) {\n  const held = await runRequired(context, edge);\n  if (held) return held;\n"
                    "  return (await agentFiles(context{gate})) ?? vary(await discoveryHeaders(context, (await runEdge(context, edge)) ?? (await context.next())));\n}\n")
WITHOUT = ("export async function onRequest(context) {\n  const held = await runRequired(context, edge);\n  if (held) return held;\n"
           "  return (await runEdge(context, edge)) ?? (await context.next());\n}\n")


class EdgeError(Exception):
    """The site's edge code can't be made: a missing kit file, bad settings, or a plugin's refusal. Nothing is written."""


def files(root, functions):
    """{path under functions/: text} for the site at `root`. `functions` must be the site's own functions/ folder: the recipe
    imports agent-files as ../plugins/, from there (Fable on site-kit#399)."""
    root = pathlib.Path(root)
    if pathlib.Path(functions).resolve() != (root / "functions").resolve():
        raise EdgeError(f"--functions must be the site's own functions/ folder ({root / 'functions'}), not {functions}")
    kit = root / ".sitekit"
    try:
        settings = json.loads((kit / "plugins.json").read_text(encoding="utf-8")) if (kit / "plugins.json").is_file() else {}
        chain = (kit / "chain.js").read_text(encoding="utf-8")
    except (OSError, ValueError) as e:
        raise EdgeError(f".sitekit/plugins.json or .sitekit/chain.js can't be read ({type(e).__name__}): run site_sync.py sync") from None
    if not isinstance(settings, dict) or not all(isinstance(v, dict) for v in settings.values()):
        raise EdgeError('.sitekit/plugins.json must be {"<plugin>": {"<setting>": value}}')
    spec = importlib.util.spec_from_file_location("sitekit_theme", kit / "theme.py")
    if spec is None or not (kit / "theme.py").is_file():
        raise EdgeError(".sitekit/theme.py is missing: run site_sync.py sync")
    theme = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(theme)
    if "only" not in inspect.signature(theme.load).parameters:  # synced before site-kit#400 (site-kit#405)
        raise EdgeError(".sitekit/theme.py is older than the kit: run site_sync.py sync")
    try:
        out = theme.load(root / "plugins", settings, only=edge_plugins(root / "plugins")).function_files(types.SimpleNamespace())
    except theme.ThemeError as e:
        raise EdgeError(str(e)) from None
    has_agent_files = (root / "plugins" / "agent-files" / "functions" / "agent-files.js").is_file()
    unguarded = dues_admin_unguarded(out)
    if unguarded:
        raise EdgeError(unguarded)
    out["_chain.js"] = chain
    # With a members gate, agent-files is told so, and refuses twins and /mcp if the gate's matcher is missing (site-kit#418).
    gate = ", { members: true }" if "plugins/members/members-data.json" in out else ""
    out["_middleware.js"] = HEAD + IMPORTS + (AGENT_FILES + WITH_AGENT_FILES.replace("{gate}", gate) if has_agent_files else WITHOUT)
    return out


def edge_plugins(plugins):
    """The plugin folders whose plugin.json has an "edge" block, by name. Only these are loaded here: a slot plugin's settings
    are its slot's config file, so loading it with plugins.json's settings would refuse a site that uses one. A plugin.json
    that can't be read is loaded anyway, so the theme names what's wrong with it."""
    names = set()
    for d in sorted(pathlib.Path(plugins).iterdir()) if pathlib.Path(plugins).is_dir() else []:
        try:
            edge = json.loads((d / "plugin.json").read_text(encoding="utf-8")).get("edge")
        except (OSError, ValueError, AttributeError):
            edge = True
        if d.is_dir() and edge:
            names.add(d.name)
    return names


def dues_admin_unguarded(out):
    """Why the dues-admin page isn't safely gated, or "" (site-kit#432): its path must sit under a members rule that names
    plans, so only the club's officers reach it. The edge refuses an ungated path too; this stops the build first."""
    data = out.get("plugins/dues-admin/dues-admin-data.json")
    if data is None:
        return ""
    path = json.loads(data)["config"]["path"]
    members = out.get("plugins/members/members-data.json")
    rules = json.loads(members)["config"]["rules"] if members else []
    if not any(path.startswith(r["prefix"]) and r["plans"] for r in rules):
        return (f'dues-admin: its path {path} must sit under a members rule with plans, e.g. "{path} plans:officers", '
                "so only the club's officers reach it")
    return ""


def listed_gated(pages, out):
    """The record's pages a members rule gates that would still be listed (in llms-full.txt, llms.txt, the sitemap and the
    twins), by path: each must say "index": false (Fable on site-kit#399). The rules are the members plugin's built data in
    `out`, matched as its match.js matches a page path: a rule's directory holds the page's path with a trailing "/"."""
    data = out.get("plugins/members/members-data.json")
    if data is None:
        return []
    rules = json.loads(data)["config"]["rules"]
    def gated(path):
        d = path.lower() if path.endswith("/") else path.lower() + "/"
        return any(d.startswith(r["prefix"]) for r in rules)
    return [p["path"] for p in pages if gated(p["path"]) and p.get("index") is not False]


def links(functions):
    """Every symlink at functions/, at functions/plugins/ or anywhere under it, found without following one (Fable on #399:
    a link to / would otherwise walk the whole disk before the build refused)."""
    functions = pathlib.Path(functions)
    found = [p for p in (functions, functions / "plugins") if p.is_symlink()]
    if found or not (functions / "plugins").is_dir():
        return found
    for dirpath, dirnames, filenames in os.walk(functions / "plugins", followlinks=False):
        found += [pathlib.Path(dirpath) / n for n in sorted(dirnames + filenames) if (pathlib.Path(dirpath) / n).is_symlink()]
    return found


def on_disk(functions):
    """What the build wrote last time: the files it owns at the top of functions/, and everything under functions/plugins/.
    Never follows a symlink: refusals() checks links() first."""
    functions = pathlib.Path(functions)
    found = []
    if (functions / "plugins").is_dir() and not links(functions):
        for dirpath, _, filenames in os.walk(functions / "plugins", followlinks=False):
            found += [pathlib.Path(dirpath) / n for n in filenames]
        found.sort()
    found += [functions / n for n in OWNED if (functions / n).is_file()]
    return {f.relative_to(functions).as_posix(): f.read_text(encoding="utf-8", errors="replace") for f in found}


def differences(out, functions):
    """The paths whose committed copy differs from `out`, or that `out` no longer makes, sorted."""
    have = on_disk(functions)
    return sorted({p for p in set(out) | set(have) if out.get(p) != have.get(p)})


def refusals(out, functions):
    """Why `out` can't be written under functions/, as messages; empty when it can. Checked before anything is written."""
    functions = pathlib.Path(functions)
    linked = links(functions)
    if linked:   # before anything walks the tree
        return [f"{p} is a symlink: the build writes no file through one" for p in linked]
    out_of_ours = sorted(set(on_disk(functions)) - set(out))
    problems = [f"functions/{rel} isn't a file the build makes: move it out of functions/plugins/ or delete it yourself; "
                "the build never deletes it" for rel in out_of_ours]
    for rel in sorted(out):
        parts = pathlib.PurePosixPath(rel).parts
        if not parts or ".." in parts or pathlib.PurePosixPath(rel).is_absolute():
            problems.append(f"functions/{rel} is outside functions/")
            continue
        at = functions
        for part in ("", *parts):
            at = at / part if part else at
            if at.is_symlink():
                problems.append(f"{at} is a symlink: the build writes no file through one")
                break
    return problems


def write(out, functions):
    """Write `out` under functions/, after refusals() found nothing. Returns the paths written."""
    functions = pathlib.Path(functions)
    found = refusals(out, functions)
    if found:
        raise EdgeError("; ".join(found))
    for rel, text in out.items():
        f = functions / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text, encoding="utf-8")
    return sorted(out)
